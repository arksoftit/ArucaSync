def mapear_clientes(origen, filas, machine, user):
    mapa = COLUMNAS_MAP["arc_clientes"]
    pares = mapa[origen]
    columnas = [destino for destino, _ in pares] + mapa["auditoria"]
    filas_mapeadas = []
    for fila in filas:
        valores = list(fila) + [machine, user, machine, user]
        filas_mapeadas.append(tuple(valores))
    return columnas, filas_mapeadas